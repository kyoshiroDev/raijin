#!/usr/bin/env node
// Writes src/environments/environment.ts from the output of
//   npx supabase projects api-keys --remote=<ref> -o json
// read on stdin. Keeps ONLY the publishable key (or the legacy anon JWT as fallback).
// Never prints a key. Refuses anything whose name/type/role mentions "service" or "secret".
//
// Usage: npx supabase projects api-keys --remote=<ref> -o json 2>/dev/null \
//          | node scripts/env-from-api-keys.mjs <ref>
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const target = 'src/environments/environment.ts';
const ref = process.argv[2];
const fail = (msg) => {
  console.error(`env-from-api-keys: ${msg}`);
  process.exit(1);
};
if (!ref || !/^[a-z0-9]{20}$/.test(ref)) fail('usage: ... | node scripts/env-from-api-keys.mjs <project-ref>');

let raw = '';
for await (const chunk of process.stdin) raw += chunk;
const start = raw.indexOf('[');
if (start < 0) fail('no JSON array on stdin.');
let keys;
try {
  keys = JSON.parse(raw.slice(start));
} catch {
  fail('stdin is not valid JSON.');
}
if (!Array.isArray(keys)) fail('expected an array of keys.');

const forbidden = /service|secret/i;
const jwtRole = (key) => {
  const parts = key.split('.');
  if (parts.length !== 3) return null;
  try {
    return JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8')).role ?? null;
  } catch {
    return null;
  }
};
const isSafe = (k) =>
  k &&
  typeof k.api_key === 'string' &&
  !forbidden.test(String(k.name ?? '')) &&
  !forbidden.test(String(k.id ?? '')) &&
  !forbidden.test(String(k.type ?? '')) &&
  !forbidden.test(String(k.description ?? '')) &&
  !forbidden.test(JSON.stringify(k.secret_jwt_template ?? {})) &&
  !k.api_key.startsWith('sb_secret_');

const safe = keys.filter(isSafe);
const publishable = safe.find((k) => k.type === 'publishable' && k.api_key.startsWith('sb_publishable_'));
const anon = safe.find((k) => k.type === 'legacy' && k.name === 'anon' && jwtRole(k.api_key) === 'anon');
const chosen = publishable ?? anon;
if (!chosen) fail('no publishable or anon key found.');

const key = chosen.api_key;
// Same final checks as scripts/write-env.mjs.
if (key.startsWith('sb_secret_')) fail('refusing a secret key.');
if (key.split('.').length === 3) {
  if (jwtRole(key) !== 'anon') fail('JWT role is not "anon".');
} else if (!key.startsWith('sb_publishable_')) {
  fail('unrecognised key format.');
}

const url = `https://${ref}.supabase.co`;
// Public VAPID key only (never the private one) from .secrets/vapid.json, if present.
let vapid = '';
if (existsSync('.secrets/vapid.json')) {
  const pub = JSON.parse(readFileSync('.secrets/vapid.json', 'utf8')).publicKey;
  if (typeof pub === 'string' && /^B[A-Za-z0-9_-]{86}$/.test(pub)) vapid = pub;
}
writeFileSync(
  target,
  `// Generated by scripts/env-from-api-keys.mjs — do not edit, do not commit.
export const environment = {
  production: false,
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(key)},
  vapidPublicKey: ${JSON.stringify(vapid)},
} as const;
`,
);
console.log(`env-from-api-keys: environment.ts written with the ${publishable ? 'publishable' : 'legacy anon'} key.`);
