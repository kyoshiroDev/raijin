#!/usr/bin/env node
// Writes src/environments/environment.ts from NG_APP_SUPABASE_URL / NG_APP_SUPABASE_ANON_KEY /
// NG_APP_VAPID_PUBLIC_KEY (Vercel env vars).
// Refuses any key that is not a public anon/publishable key, so a service_role key can never ship to the browser.
import { existsSync, writeFileSync } from 'node:fs';

const target = 'src/environments/environment.ts';
const url = process.env.NG_APP_SUPABASE_URL;
const key = process.env.NG_APP_SUPABASE_ANON_KEY;
const vapid = process.env.NG_APP_VAPID_PUBLIC_KEY ?? '';
const fail = (msg) => {
  console.error(`write-env: ${msg}`);
  process.exit(1);
};

if (!url || !key) {
  if (existsSync(target)) {
    console.log('write-env: env vars absent, keeping existing environment.ts');
    process.exit(0);
  }
  fail('NG_APP_SUPABASE_URL and NG_APP_SUPABASE_ANON_KEY are required (or create environment.ts from the example).');
}

const isLocal = /^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(url);
if (!isLocal && !/^https:\/\/[a-z0-9]{20}\.supabase\.co$/.test(url)) fail('invalid Supabase URL.');

if (key.startsWith('sb_secret_')) fail('this is a SECRET key. Use the publishable/anon key only.');
const parts = key.split('.');
if (parts.length === 3) {
  let role;
  try {
    role = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8')).role;
  } catch {
    fail('anon key is not a valid JWT.');
  }
  if (role !== 'anon') fail(`key role is "${role}". Only the anon key may be used in the front.`);
} else if (!key.startsWith('sb_publishable_')) {
  fail('unrecognised key format.');
}

// VAPID public key: base64url of an uncompressed P-256 point (65 bytes → 87 chars). Public by design.
if (vapid && !/^B[A-Za-z0-9_-]{86}$/.test(vapid)) fail('NG_APP_VAPID_PUBLIC_KEY is not a valid VAPID public key.');

const production = process.env.VERCEL_ENV === 'production';
writeFileSync(
  target,
  `// Generated by scripts/write-env.mjs — do not edit, do not commit.
export const environment = {
  production: ${production},
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(key)},
  vapidPublicKey: ${JSON.stringify(vapid)},
} as const;
`,
);
console.log(`write-env: environment.ts written (production=${production}).`);
